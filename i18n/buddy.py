#!/usr/bin/env python3
"""Buddy web app copy: i18n/buddy/<lang>.json → public/buddy/strings.js.

    python3 i18n/buddy.py check [lang...]   # same keys, same {placeholders} and <br> as English
    python3 i18n/buddy.py build             # write public/buddy/strings.js (languages that exist)

The app picks the language itself (public/buddy/i18n.js), so there are no per-language copies.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from render import LANGS  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'buddy')
OUT = os.path.join(HERE, '..', 'public', 'buddy', 'strings.js')


def load(code):
    p = os.path.join(SRC, f'{code}.json')
    if not os.path.exists(p):
        return None
    return {k: v for k, v in json.load(open(p, encoding='utf-8')).items() if not k.startswith('_')}


def marks(s):
    return sorted(re.findall(r'\{\w+\}|<br>', s))


def check(codes):
    en, bad = load('en'), 0
    for code in codes or [c for c, *_ in LANGS if c != 'en']:
        d = load(code)
        if d is None:
            print(f'{code}: no file'); bad += 1; continue
        probs = [f'{k}: missing' for k in en if k not in d]
        probs += [f'{k}: placeholders/<br> differ ({d[k]})' for k in en if k in d and marks(d[k]) != marks(en[k])]
        probs += [f'{k}: unknown key' for k in d if k not in en]
        bad += bool(probs)
        print(f'{code}: ' + ('OK' if not probs else '\n  ' + '\n  '.join(probs)))
    return bad


def build():
    data = {c: load(c) for c, *_ in LANGS if load(c)}
    body = json.dumps(data, ensure_ascii=False, indent=1)
    open(OUT, 'w', encoding='utf-8').write(
        '// Generated by i18n/buddy.py from i18n/buddy/<lang>.json — edit those, not this.\n'
        f'export const STRINGS = {body};\n')
    print('buddy strings:', ', '.join(data))


if __name__ == '__main__':
    cmd, *rest = sys.argv[1:] or ['build']
    sys.exit(check(rest) and 1 if cmd == 'check' else build())
